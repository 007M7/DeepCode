/** Translation key shared by both renderer dictionaries. */
export type I18nKey = keyof typeof messages['en-US']

/**
 * Return a localized renderer string, falling back to English and then the key.
 * @param locale - The active renderer locale.
 * @param key - The dictionary key to resolve.
 * @returns The localized string for the requested key.
 */
export function translate(locale: Locale, key: I18nKey): string {
  return messages[locale][key]
}
